"""
fbx_writer.py
-------------
Pure-Python ASCII FBX writer. Hiçbir external dependency yok (sadece numpy).

FBX ASCII Format 7400 üretir — Maya 2026, UE5, Blender, MotionBuilder
hepsi bunu import eder.

Kullanım:
  from fbx_writer import write_fbx_animation
  write_fbx_animation(
      output_path="idle.fbx",
      bone_hierarchy=[...],   # [(bone_name, parent_name, offset_xyz), ...]
      bone_order=[...],       # animation data sırası
      animation_data={...},   # bone_name -> {pos: (T,3), rot: (T,3)}
      fps=30,
      n_frames=150,
  )

FBX koordinat sistemi:
  Default: Y up, -Z forward, +X right (Maya/Unreal uyumlu)
  Birim: santimetre

Notlar:
  - ASCII FBX Maya tarafından her zaman kabul edilir
  - Bone'lar LimbNode tipinde yazılır
  - Animation curves her bone için Lcl Translation + Lcl Rotation
  - FBX'te rotation order: XYZ (Euler)
"""

from typing import Dict, List, Tuple, Optional
import numpy as np
import time


# ═══════════════════════════════════════════════════════════════════════════════
# ID GENERATOR
# ═══════════════════════════════════════════════════════════════════════════════

class IDGen:
    """FBX için benzersiz int64 ID'ler üretir."""
    def __init__(self, start: int = 1000000):
        self.counter = start

    def next(self) -> int:
        self.counter += 1
        return self.counter


# ═══════════════════════════════════════════════════════════════════════════════
# FBX WRITER
# ═══════════════════════════════════════════════════════════════════════════════

class FBXWriter:
    def __init__(self):
        self.lines: List[str] = []
        self.indent = 0
        self.ids = IDGen()

    def w(self, line: str):
        self.lines.append("\t" * self.indent + line)

    def open(self, name: str):
        self.w(name + " {")
        self.indent += 1

    def close(self):
        self.indent -= 1
        self.w("}")

    def render(self) -> str:
        return "\n".join(self.lines) + "\n"


# ═══════════════════════════════════════════════════════════════════════════════
# HEADER & GLOBAL SETTINGS
# ═══════════════════════════════════════════════════════════════════════════════

def write_header(w: FBXWriter):
    """FBX file header — sabit kısımlar."""
    t = time.localtime()
    w.w("; FBX 7.4.0 project file")
    w.w("; Generated by needlecrawler idle composer")
    w.w("")
    w.open("FBXHeaderExtension:")
    w.w("FBXHeaderVersion: 1003")
    w.w("FBXVersion: 7400")
    w.open("CreationTimeStamp:  ")
    w.w("Version: 1000")
    w.w(f"Year: {t.tm_year}")
    w.w(f"Month: {t.tm_mon}")
    w.w(f"Day: {t.tm_mday}")
    w.w(f"Hour: {t.tm_hour}")
    w.w(f"Minute: {t.tm_min}")
    w.w(f"Second: {t.tm_sec}")
    w.w("Millisecond: 0")
    w.close()
    w.w('Creator: "compose_idle.py — pure-Python FBX ASCII writer"')
    w.open("SceneInfo: \"SceneInfo::GlobalInfo\", \"UserData\"")
    w.w('Type: "UserData"')
    w.w("Version: 100")
    w.open("MetaData:")
    w.w("Version: 100")
    w.w('Title: ""')
    w.w('Subject: ""')
    w.w('Author: ""')
    w.w('Keywords: ""')
    w.w('Revision: ""')
    w.w('Comment: ""')
    w.close()
    w.close()
    w.close()
    w.w("")


def write_global_settings(w: FBXWriter, fps: int):
    """Y-up, cm, 30fps default ayarları."""
    w.open("GlobalSettings:")
    w.w("Version: 1000")
    w.open("Properties70:")
    # Y up, -Z forward (Maya/Unreal default)
    w.w('P: "UpAxis", "int", "Integer", "",1')
    w.w('P: "UpAxisSign", "int", "Integer", "",1')
    w.w('P: "FrontAxis", "int", "Integer", "",2')
    w.w('P: "FrontAxisSign", "int", "Integer", "",1')
    w.w('P: "CoordAxis", "int", "Integer", "",0')
    w.w('P: "CoordAxisSign", "int", "Integer", "",1')
    w.w('P: "OriginalUpAxis", "int", "Integer", "",1')
    w.w('P: "OriginalUpAxisSign", "int", "Integer", "",1')
    # Unit: cm
    w.w('P: "UnitScaleFactor", "double", "Number", "",1')
    w.w('P: "OriginalUnitScaleFactor", "double", "Number", "",1')
    # Time mode
    w.w('P: "AmbientColor", "ColorRGB", "Color", "",0,0,0')
    w.w('P: "DefaultCamera", "KString", "", "", "Producer Perspective"')
    w.w('P: "TimeMode", "enum", "", "",11')  # 11 = custom fps
    w.w('P: "TimeProtocol", "enum", "", "",2')
    w.w('P: "SnapOnFrameMode", "enum", "", "",0')
    w.w(f'P: "CustomFrameRate", "double", "Number", "",{fps}')
    w.close()  # Properties70
    w.close()  # GlobalSettings
    w.w("")


# ═══════════════════════════════════════════════════════════════════════════════
# DEFINITIONS — kaç tane her tipten object var
# ═══════════════════════════════════════════════════════════════════════════════

def write_definitions(w: FBXWriter, n_bones: int, n_anim_curves: int,
                      n_anim_curve_nodes: int):
    """Definitions bloğu — Maya için gerekli template'ler."""
    total = (
        1 +                 # GlobalSettings
        1 +                 # AnimationStack
        1 +                 # AnimationLayer
        n_bones * 2 +       # Model (LimbNode) + NodeAttribute per bone
        n_anim_curves +     # AnimationCurve
        n_anim_curve_nodes  # AnimationCurveNode
    )

    w.open("Definitions:")
    w.w("Version: 100")
    w.w(f"Count: {total}")

    # GlobalSettings
    w.open("ObjectType: \"GlobalSettings\"")
    w.w("Count: 1")
    w.close()

    # Model (for bones)
    if n_bones > 0:
        w.open("ObjectType: \"Model\"")
        w.w(f"Count: {n_bones}")
        w.open("PropertyTemplate: \"FbxNode\"")
        w.open("Properties70:")
        w.w('P: "RotationActive", "bool", "", "",1')
        w.w('P: "InheritType", "enum", "", "",1')
        w.w('P: "ScalingMax", "Vector3D", "Vector", "",0,0,0')
        w.w('P: "DefaultAttributeIndex", "int", "Integer", "",-1')
        w.w('P: "Lcl Translation", "Lcl Translation", "", "A",0,0,0')
        w.w('P: "Lcl Rotation", "Lcl Rotation", "", "A",0,0,0')
        w.w('P: "Lcl Scaling", "Lcl Scaling", "", "A",1,1,1')
        w.close()
        w.close()
        w.close()

    # NodeAttribute for LimbNode
    if n_bones > 0:
        w.open("ObjectType: \"NodeAttribute\"")
        w.w(f"Count: {n_bones}")
        w.open("PropertyTemplate: \"FbxSkeleton\"")
        w.open("Properties70:")
        w.w('P: "Color", "ColorRGB", "Color", "",0.8,0.8,0.8')
        w.w('P: "Size", "double", "Number", "",100')
        w.w('P: "LimbLength", "double", "Number", "H",1')
        w.close()
        w.close()
        w.close()

    # AnimationStack
    w.open("ObjectType: \"AnimationStack\"")
    w.w("Count: 1")
    w.open("PropertyTemplate: \"FbxAnimStack\"")
    w.open("Properties70:")
    w.w('P: "Description", "KString", "", "", ""')
    w.w('P: "LocalStart", "KTime", "Time", "",0')
    w.w('P: "LocalStop", "KTime", "Time", "",0')
    w.w('P: "ReferenceStart", "KTime", "Time", "",0')
    w.w('P: "ReferenceStop", "KTime", "Time", "",0')
    w.close()
    w.close()
    w.close()

    # AnimationLayer
    w.open("ObjectType: \"AnimationLayer\"")
    w.w("Count: 1")
    w.open("PropertyTemplate: \"FbxAnimLayer\"")
    w.open("Properties70:")
    w.w('P: "Weight", "Number", "", "A",100')
    w.w('P: "Mute", "bool", "", "",0')
    w.w('P: "Solo", "bool", "", "",0')
    w.w('P: "Lock", "bool", "", "",0')
    w.w('P: "Color", "ColorRGB", "Color", "",0.8,0.8,0.8')
    w.w('P: "BlendMode", "enum", "", "",0')
    w.w('P: "RotationAccumulationMode", "enum", "", "",0')
    w.w('P: "ScaleAccumulationMode", "enum", "", "",0')
    w.w('P: "BlendModeBypass", "ULongLong", "", "",0')
    w.close()
    w.close()
    w.close()

    # AnimationCurveNode
    if n_anim_curve_nodes > 0:
        w.open("ObjectType: \"AnimationCurveNode\"")
        w.w(f"Count: {n_anim_curve_nodes}")
        w.open("PropertyTemplate: \"FbxAnimCurveNode\"")
        w.open("Properties70:")
        w.close()
        w.close()
        w.close()

    # AnimationCurve
    if n_anim_curves > 0:
        w.open("ObjectType: \"AnimationCurve\"")
        w.w(f"Count: {n_anim_curves}")
        w.close()

    w.close()  # Definitions
    w.w("")


